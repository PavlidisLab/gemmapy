# -*- coding: utf-8 -*-
"""Retry transient Gemma responses.

Gemma answers with 503 and a ``Retry-After`` header when it is shedding load.
That is the server telling us when to come back, so it is worth honouring for as
long as it keeps asking rather than failing the call. Other transient
conditions (429, 500, and connection-level failures that the SDK reports as
status 0) get a small fixed number of re-tries instead.

This lives here rather than in ``gemmapy/sdk`` because everything under that
directory is regenerated by ``sdk-gen/generate-sdk.sh`` and hand edits would be
lost. ``RESTClientObject.request`` is the single choke point every call passes
through -- the verb helpers (``GET``, ``POST``, ...) all delegate to it, and so
does ``GemmaPy.filter_properties`` -- so subclassing it and swapping the
instance in covers the whole surface without touching generated code.

The gemma.R package does the same thing in ``R/body.R``; keep the two in step.
"""
import email.utils
import logging
import time
from datetime import datetime, timezone

from gemmapy import sdk
from gemmapy.sdk.rest import ApiException

logger = logging.getLogger(__name__)

#: Statuses worth another attempt. 0 is what the SDK reports for an SSL or
#: connection failure, which is gemma.R's ``is.null(response$status_code)``.
RETRY_STATUSES = (0, 429, 500, 503)

#: Attempts for a transient response the server gave us no schedule for.
MAX_UNDIRECTED_RETRIES = 3

#: Seconds to wait when the server did not tell us how long to wait.
UNDIRECTED_WAIT = 5

#: Only re-send requests that can be repeated without side effects. gemma.R can
#: retry everything because its generated surface is GET-only; ours also carries
#: the admin, ticket and workflow endpoints, where re-sending a POST that failed
#: with a 500 could apply a curation action twice.
IDEMPOTENT_METHODS = frozenset({'GET', 'HEAD', 'OPTIONS'})


def retry_after(headers):
    """Seconds the server asked us to wait, or None.

    Reads the ``Retry-After`` response header, accepting both the delay in
    seconds and the HTTP-date forms. The delay is rounded to whole seconds and
    floored at one so a server-directed re-try cannot spin.
    """
    if not headers:
        return None
    # urllib3 returns an HTTPHeaderDict, which is case insensitive, but a plain
    # dict from a stub or an older response is not.
    value = headers.get('Retry-After')
    if value is None:
        value = headers.get('retry-after')
    if value is None:
        return None

    try:
        seconds = float(value)
    except (TypeError, ValueError):
        try:
            when = email.utils.parsedate_to_datetime(value)
        except (TypeError, ValueError):
            return None
        if when is None:
            return None
        if when.tzinfo is None:
            when = when.replace(tzinfo=timezone.utc)
        seconds = (when - datetime.now(timezone.utc)).total_seconds()

    if seconds != seconds:  # NaN
        return None
    return max(round(seconds), 1)


class RetryingRESTClient(sdk.rest.RESTClientObject):
    """A REST client that waits and re-tries instead of raising on a transient
    response. See the module docstring."""

    def request(self, method, url, **kwargs):
        undirected = 0
        while True:
            try:
                return super().request(method, url, **kwargs)
            except ApiException as e:
                if e.status not in RETRY_STATUSES:
                    raise
                if method.upper() not in IDEMPOTENT_METHODS:
                    raise

                # A 503 carrying Retry-After is the server scheduling us, so it
                # does not count against the attempt limit.
                directed = retry_after(e.headers) if e.status == 503 else None
                if directed is None:
                    if undirected >= MAX_UNDIRECTED_RETRIES:
                        raise
                    undirected += 1
                    wait = UNDIRECTED_WAIT
                    logger.warning(
                        'No valid response from Gemma (%s). Retrying in %s seconds.',
                        e.status, wait)
                else:
                    wait = directed
                    logger.warning(
                        'High traffic in Gemma. Retrying in %s seconds.', wait)

                time.sleep(wait)
